def _build_system_prompt(
    *,
    voice_samples: list[str],
    page_context: str | None,
    available_surfaces: list[str],
    persona_core: str | None = None,
    profile_text: str | None = None,
    display_name: str | None = None,
    agent_id: str = "artemis",
    recent_meeting_context: str | None = None,
    session_id: str = "",
    speaker_name: str | None = None,
    participants: list[str] | None = None,
    is_personal_slack_dm: bool = False,
    okr_reconcile_context: str | None = None,
    recent_outbound_texts: list[str] | None = None,
) -> str:
    profile = load_agent_profile("artemis")
    persona_core = profile.persona_core if persona_core is None else persona_core
    profile_text = profile.profile_text if profile_text is None else profile_text
    display_name = profile.display_name if display_name is None else display_name

    # Lead with the high-priority distilled persona rules.
    parts = [persona_core] if persona_core else []

    # Append the full personality profile as richer background detail.
    if profile_text:
        parts.append("## Full personality profile (background reference)\n" + profile_text)

    if voice_samples:
        samples_text = "\n".join(f'- "{line}"' for line in voice_samples)
        parts.append(
            "## Characteristic phrases (calibration only)\n"
            "These calibrate your register and rhythm. Never quote them verbatim or "
            "near-verbatim. Generate fresh lines in this spirit:\n" + samples_text
        )

    if page_context:
        parts.append(f"## Current operator context\n{page_context}")

    if available_surfaces:
        surfaces_str = ", ".join(sorted(available_surfaces))
        parts.append(f"## Available surfaces (your tools are gated by these)\n{surfaces_str}")

    # Recent meeting context (J6d): inject if a meeting ended within the last 4 hours.
    # H4: framed as LLM-generated inferences with provenance so action items
    # aren't treated as firm commitments.
    if recent_meeting_context:
        parts.append(
            "## Recent meeting summaries (LLM-generated by the meeting summarizer — "
            "treat as inferences)\n\n"
            "The following summaries were produced by the meeting_summarizer LLM after "
            "each meeting. Bullets and action_items reflect what the analyzer INFERRED "
            "from the transcript, not necessarily verbatim commitments.\n\n"
            "Before treating any action_item as a firm commitment by the user or another "
            "person:\n"
            "- For action_items with `owner` set: confirm with the user before acting\n"
            "- For action_items with `due` set: do not autonomously schedule reminders "
            "without user approval\n"
            "- If asked about a specific meeting decision, retrieve the raw transcript "
            "via granola tools rather than trusting the summary alone\n\n"
            f"{recent_meeting_context}"
        )

    # OKR reconcile context: injected when a live check-in breadcrumb exists for
    # this session's speaker.  Instructs Artemis to map the word-dump to KRs and
    # CALL update_okr_krs (layer-3 batch tool) — calling IS the proposal; the
    # tool suspends and waits for the operator's explicit 'go' before writing.
    if okr_reconcile_context:
        parts.append(okr_reconcile_context)

    # ── Human-voice nudge (agent-agnostic) ──────────────────────────────────
    # Applied to every agent on every turn.  Does NOT override persona content;
    # it reinforces structural habits that make any agent sound human.
    parts.append(
        "## Human communication rules (all agents, every turn)\n"
        "- Address people by their first name naturally when you know it — weave it "
        "in, don't open every message the same way.\n"
        "- Vary your sentence openings. Never start two consecutive messages the same way.\n"
        "- Never send canned, templated, or copy-pasted-sounding text.\n"
        "- Sound like a real person: concrete, warm where it fits, specific rather than generic."
    )

    # ── Acting vs. describing (agent-agnostic) ───────────────────────────────
    # Root fix for the recurring "agent narrates an action but nothing happens"
    # bug (Callie: 'Argus is on it' with no dispatch_research call; Artemis:
    # 'send tools aren't wired' when create_event/send_slack ARE in her toolset).
    # The infra works — the agents simply weren't calling their tools. This makes
    # tool-calling the only way to act, and forbids confabulating missing tools.
    parts.append(
        "## Acting means calling a tool (all agents, every turn)\n"
        "- To DO anything with an effect — schedule, send, dispatch, write, react — "
        "you must CALL the tool that does it. Describing the action in words is not "
        "performing it.\n"
        "- For side-effecting tools, calling is still safe: the system stages the call "
        "and hands you back a confirmation prompt to relay. Nothing executes until the "
        "operator confirms, so calling IS how you propose. Don't write a prose proposal "
        "instead of calling.\n"
        "- Never tell the operator something is done, or that you've started it (e.g. "
        '"it\'s on it", "I\'ve queued it"), unless you actually called the tool this turn.\n'
        '- Never claim a capability is missing or "not wired." If a tool is in your '
        "toolset, use it. If the call errors, report the actual error — don't invent a "
        "limitation."
    )

    # ── Anti-repetition: recent outbound messages ────────────────────────────
    # When the last few assistant messages in this session are available, inject
    # them so the LLM actively avoids repeating itself.  This prevents two
    # back-to-back channel-join welcomes from being verbatim identical.
    if recent_outbound_texts:
        quoted = "\n".join(f'- "{t}"' for t in recent_outbound_texts)
        parts.append(
            "## Your recent messages in this channel (do NOT repeat or closely echo these)\n"
            "These are your last outbound messages. Read them and deliberately vary your "
            "wording, structure, and opening so your next reply feels fresh and distinct:\n"
            + quoted
        )

    # Slack-originated session: establish the conversational context.
    if session_id.startswith("slack-"):
        if speaker_name:
            who = f" You are talking to {speaker_name}."
        else:
            # Say so explicitly rather than leaving a blank. With nothing here,
            # Callie addressed Josh as "Jon" -- the model filled the gap with the
            # only human it had ever been told about (2026-08-12).
            who = (
                " You do NOT know who is speaking. Do not guess a name, and do "
                "not assume it is Jon."
            )
        if participants:
            # Who is in the room, resolved from verified Slack ids. Prefer these
            # people over any directory name-search: asked to "tell Josh the top
            # signals" while Josh Mukai sat in that very channel, Callie searched
            # the whole company and offered "Josh Smith (0.9 confidence)".
            who += (
                " People in this conversation: "
                + ", ".join(participants)
                + ". When someone refers to a person by first name, resolve it "
                "against THIS list first -- these are verified participants. Only "
                "search the wider directory if nobody here matches."
            )
        parts.append(
            "**You are responding in Slack.** The operator @-mentioned you directly. "
            "**Assume they are addressing you and respond on-topic.** "
            'Do not ask "Are you talking to me?" — they are. '
            "Be concise; Slack rewards short replies. "
            "**Do NOT use markdown tables** (`| Field | Value |` pipe-table syntax) — "
            "Slack renders them as raw pipes and dashes. "
            "Use **bold labels** with short bullet lines or plain sentences instead." + who
        )
        if is_personal_slack_dm and agent_id == "artemis":
            parts.append(
                "## Slack DM scope\n"
                "This 1:1 Slack DM is for personal support, app/ops issues, and upgrades. "
                "You are Jon's orchestrator and personal partner here. "
                "Do not volunteer marketing in this DM. Marketing is Callie's lane and only "
                "comes here if Jon explicitly asks."
            )

    return "\n\n".join(parts)


async def get_recent_summaries_with_provenance(
    db_session: Any | None, hours: int = 4
) -> list[dict[str, Any]]:
    """Return recent meeting summaries with explicit LLM-provenance metadata (H4).

    Each item is `{meeting_id, title, summary, action_items, provenance}`.
    `provenance.source="llm_meeting_summarizer"`, `legacy_format=True` when the
    stored `action_items` would not pass the current Pydantic shape.

    Lossless invariant: existing rows are NEVER mutated — `legacy_format` is a
    read-time marker only.
    """
    import artemis.db as _db
    from artemis.meetings.summarizer import get_recent_summaries
    from artemis.meetings.summary_schemas import validate_existing

    async def _fetch(session: Any) -> list[Any]:
        return cast(list[Any], await get_recent_summaries(session, hours=hours))

    if db_session is not None:
        rows = await _fetch(db_session)
    else:
        async with _db.SessionLocal() as session:
            rows = await _fetch(session)

    result: list[dict[str, Any]] = []
    for row in rows:
        is_valid, _ = validate_existing(row.action_items)
        result.append(
            {
                "meeting_id": row.granola_id,
                "title": row.title,
                "summary": row.summary,
                "action_items": row.action_items,
                "provenance": {
                    "source": "llm_meeting_summarizer",
                    "generated_at": row.created_at.isoformat() if row.created_at else None,
                    "transcript_truncated_at_chars": 6000,
                    "legacy_format": not is_valid,
                },
            }
        )
    return result


async def _get_recent_meeting_context(db_session: Any | None) -> str | None:
    """Return a one-liner summary of meetings ended in the last 4 hours, or None.

    Used by handle_turn to inject meeting context into the system prompt so
    Artemis is aware of what Jon just finished without being told. H4 framing
    in `_build_system_prompt` flags these as LLM inferences with provenance.
    """
    try:
        items = await get_recent_summaries_with_provenance(db_session, hours=4)
        if not items:
            return None

        lines: list[str] = []
        for item in items:
            summary_text = item["summary"]
            bullet_lines = [
                line.strip() for line in summary_text.splitlines() if line.strip().startswith("-")
            ][:3]
            bullets_short = " ".join(bullet_lines) if bullet_lines else summary_text[:200]
            legacy = " [legacy_format]" if item["provenance"]["legacy_format"] else ""
            lines.append(f'You just finished "{item["title"]}"{legacy}. Summary: {bullets_short}')
        return "\n".join(lines)
    except Exception:
        logger.debug("Failed to fetch recent meeting context", exc_info=True)
        return None


async def _get_okr_reconcile_context(
    speaker_id: str | None,
    db_session: Any | None,
) -> str | None:
    """Return OKR-reconcile system context if a live check-in breadcrumb exists.

    When the Friday check-in fires, it persists a breadcrumb keyed to Jon's
    Slack user ID.  While that breadcrumb is live (not expired, not completed),
    we inject context into the system prompt so the next DM reply gets mapped
    to specific KRs and `stage_okr_updates` is called.  Staging does NOT apply;
    it records the proposed updates on the breadcrumb and pauses for the
    operator's explicit 'go' (applied server-side in route_inbound).  This is
    the path that works on the claude-code subscription surface, where the
    layer-3 write tools (update_okr_kr/update_okr_krs) are not reachable.

    Returns None when no live breadcrumb exists (normal DM path, no injection).
    Failure-isolated: any DB/import error returns None so chat is never broken.
    """
    if not speaker_id:
        return None
    try:
        import artemis.db as _db
        from artemis.proactivity.repository import get_live_okr_checkin_breadcrumb

        if db_session is not None:
            crumb = await get_live_okr_checkin_breadcrumb(db_session, speaker_id)
        else:
            async with _db.SessionLocal() as session:
                crumb = await get_live_okr_checkin_breadcrumb(session, speaker_id)

        if crumb is None:
            return None

        # Build the reconcile context block from the snapshot.
        snapshot = crumb.kr_snapshot or []
        if not snapshot:
            kr_list = "(no KR snapshot available)"
        else:
            lines = []
            for entry in snapshot:
                obj_title = str(entry.get("objective_title") or "").strip()
                kr_title = str(entry.get("kr_title") or "").strip()
                prog = int(entry.get("prog") or 0)
                target = str(entry.get("target_text") or "").strip()
                target_str = f" (target: {target})" if target else ""
                lines.append(
                    f"  KR {entry.get('kr_id')}: *{obj_title}* > *{kr_title}* "
                    f"— currently {prog}%{target_str}"
                )
            kr_list = "\n".join(lines)

        return (
            "## OKR check-in reconcile context\n\n"
            "You ran a Friday OKR check-in earlier. The operator's reply is their "
            "word-dump of what they moved this week. Your job:\n\n"
            "1. Engage with the substance of what they describe (be helpful, warm, on-topic).\n"
            "2. ALSO: map concrete accomplishments to SPECIFIC KRs from the snapshot below. "
            "Do NOT invent KRs or fabricate progress. If something doesn't map, say so.\n"
            "3. **CALL `stage_okr_updates` with ALL mapped updates in a single call**, "
            f"passing speaker_id={speaker_id!r} and updates=[{{kr_id, progress, basis, bullet}}, ...]. "
            "Stage everything in one call, not one call per KR.\n"
            "   - `stage_okr_updates` does NOT apply anything and writes ZERO KR rows. "
            "It records the proposed updates and pauses for the operator's explicit 'go'. "
            "After you stage, tell the operator what you staged and ask them to say 'go' "
            "to apply or 'no' to discard. The apply happens server-side after 'go'.\n"
            "   - Do NOT describe the updates only in prose and wait. Make the "
            "`stage_okr_updates` call so the operator can confirm.\n"
            "   - Never claim `stage_okr_updates` is unavailable — it is wired and is the "
            "supported check-in path on this surface. (The layer-3 `update_okr_kr` / "
            "`update_okr_krs` write tools are not reachable here; use `stage_okr_updates`.)\n"
            "4. Each staged update MUST cite the operator's own words as `basis`. "
            "Empty-basis and unknown-KR items are dropped automatically.\n"
            "   For each update, also include a concise `bullet` field: a SHORT one-line "
            "scannable summary of the accomplishment, grounded in the operator's own words "
            "(no fabrication, no new claims). Example: if the operator said 'brand hub is "
            "live on our server with all guidelines', the bullet might be 'Brand hub live "
            "on server with version-controlled guidelines'. If you are unsure how to condense "
            "it, fall back to a trimmed `basis`. The bullet is shown to the operator in the "
            "proposal (before 'go') and written to the KR's done_bullets on apply.\n"
            "5. PREFER STAGING. If the message describes ANY work / accomplishments / "
            "progress, treat it as a word-dump and `stage_okr_updates` — even if it opens "
            "or closes with a courtesy like 'hi', 'thanks', or 'thank you'. A polite "
            "greeting wrapped around a work update is NOT a sign-off.\n"
            "   Only call `complete_okr_checkin` (with "
            f"speaker_id={speaker_id!r}) when the message is PURELY a closing "
            "acknowledgement with NO reportable work (e.g. just 'that\\'s all',  "
            "'nothing else', 'done for now'), OR is clearly an unrelated new topic. When "
            "in doubt, stage rather than close. After a genuine close, do not keep "
            "injecting reconcile context.\n\n"
            f"Current KR snapshot:\n{kr_list}\n\n"
            "Reconcile their word-dump to these KRs, cite their words as basis, "
            "and CALL `stage_okr_updates` to stage the batch — then ask the operator "
            "to say 'go' to apply or 'no' to discard."
        )
    except Exception:
        logger.debug("_get_okr_reconcile_context failed — skipping injection", exc_info=True)
        return None


