async def _load_session_context(
    *,
    session_id: str,
    db_session: Any | None,
    all_surfaces: set[str],
    trusted_agent_id: str | None = None,
) -> _SessionContext:
    """Load session context.

    Parameters
    ----------
    trusted_agent_id:
        When provided (web-turn path), this value GOVERNS tool/memory gating — it
        overrides the persisted session metadata.  Derived server-side from the
        live caller's verified identity, so it cannot be spoofed via stale metadata.
        When None (Slack path, tests, resume path), falls back to persisted metadata
        with a FAIL-CLOSED default of "callie" (not "artemis").
    """
    metadata: dict[str, Any] = {}
    try:
        import artemis.db as _db
        from artemis.floating_artemis.repository import get_session_by_id

        if db_session is not None:
            row = await get_session_by_id(db_session, session_id)
        else:
            async with _db.SessionLocal() as session:
                row = await get_session_by_id(session, session_id)
        metadata_raw = getattr(row, "metadata_", {}) or {}
        if isinstance(metadata_raw, dict):
            metadata = metadata_raw
    except Exception:
        logger.debug("Could not load session metadata for session %s", session_id, exc_info=True)

    if trusted_agent_id is not None:
        # Live-identity-derived: use directly, normalise only.
        agent_id = (
            trusted_agent_id.strip().lower()
            if isinstance(trusted_agent_id, str) and trusted_agent_id.strip()
            else "callie"
        )
        logger.debug(
            "_load_session_context: using trusted_agent_id=%r for session %s (overrides metadata)",
            agent_id,
            session_id,
        )
    else:
        # Slack path / tests / resume: read from persisted metadata.
        # FAIL-CLOSED: default to "callie" (marketing-only), never "artemis".
        raw_agent_id = (
            metadata.get("agent_id", "callie") if isinstance(metadata, dict) else "callie"
        )
        agent_id = (
            raw_agent_id.strip().lower()
            if isinstance(raw_agent_id, str) and raw_agent_id.strip()
            else "callie"
        )
    scoped_surfaces = resolve_surface_scope(
        all_surfaces=all_surfaces,
        session_id=session_id,
        metadata=metadata,
    )
    return _SessionContext(
        metadata=metadata,
        available_surfaces=scoped_surfaces,
        is_personal_slack_dm=is_personal_slack_dm_session(session_id, metadata),
        agent_id=agent_id,
    )


def _collect_tools_used(result: RunResult) -> list[str]:
    """Return the deduped, ordered list of tool names invoked during a turn.

    Merges two sources, because the two provider paths surface tool calls in
    completely different places (OBS-1):

    - **Anthropic path**: ``run_turn`` executes tool_use rounds itself, so
      ``ToolUseBlock``s land directly in ``result.messages``. Scanned here
      exactly as before this fix — this source, and this path, are unchanged.
    - **claude-code MCP path** (Builder / Floating Artemis — i.e. every
      Slack-facing agent: Callie, Kai, Artemis): the CLI runs its OWN internal
      tool loop inside the subprocess and returns only a final text result,
      so no ``ToolUseBlock`` ever reaches ``result.messages`` for this path —
      that gap is the whole reason ``agent_traces.tools_used`` was ``[]`` for
      30+ days straight. ``run_turn`` recovers this from the adapter's
      stream-json parse and threads it through
      ``result.metadata["tool_calls"]`` (see ``artemis/agent/loop.py`` and
      ``artemis/providers/claude_code/adapter.py::_parse_stream_json``);
      merged in below.

    In practice exactly one source is non-empty for any given turn (a turn
    uses exactly one adapter), but both are merged the same way regardless:
    first-occurrence-wins dedup, in encounter order.

    A tool name that failed at least once is recorded as ``"<name>:error"``
    rather than a bare name. There is no separate error column to use instead
    — no migration; ``agent_traces.tools_used`` stays the ``JSONB`` array of
    strings it already is — and a name-only list would make a tool that ran
    and errored look identical to a clean success, which is exactly the
    failure mode this instrument exists to catch (a tool that "ran" and
    errored is the case that matters most; see the OBS-1 brief).
    """
    errors: dict[str, bool] = {}

    for msg in result.messages:
        if msg.role != "assistant":
            continue
        for block in msg.content:
            if isinstance(block, ToolUseBlock) and block.name not in errors:
                errors[block.name] = False

    tool_calls = cast(list[ToolCallRecord], result.metadata.get("tool_calls") or [])
    for call in tool_calls:
        if call.name not in errors:
            errors[call.name] = call.is_error
        elif call.is_error:
            errors[call.name] = True

    return [f"{name}:error" if is_error else name for name, is_error in errors.items()]


# ── Main entry point ──────────────────────────────────────────────────────────


async def handle_turn(
    *,
    session_id: str,
    user_text: str,
    reasoning_effort: str | None = None,
    speed_tier: str | None = None,
    adapter: ModelAdapter | None = None,
    owner_user_id: int | None = None,
    speaker_name: str | None = None,
    speaker_id: str | None = None,
    participants: list[str] | None = None,
    db_session: Any | None = None,
    trusted_agent_id: str | None = None,
) -> TurnResult:
    """Run one user turn for the given Floating Artemis session.

    Parameters
    ----------
    session_id:
        The floating_artemis_sessions.session_id key.
    user_text:
        The operator's message.
    adapter:
        Optional ModelAdapter override (for tests). Defaults to AnthropicAdapter.
    owner_user_id:
        Owner user ID for surface filtering and memory queries.
    speaker_name:
        Display name of the person speaking (e.g. resolved from the Slack user
        cache for inbound DMs). Threaded into the system prompt so Artemis
        addresses the operator by name. None for the web UI / unknown speakers.
    speaker_id:
        Stable platform identifier for the speaker (e.g. Slack user ID such as
        ``U01ABCDEF``).  Used alongside ``speaker_name`` for per-person memory
        attribution.  None for the web UI / unknown speakers.
    db_session:
        Optional SQLAlchemy AsyncSession (for tests). If None, a new session is
        opened from SessionLocal per DB operation.
    trusted_agent_id:
        M3 identity binding: when set, this value GOVERNS scope gating for the
        entire turn, overriding whatever agent_id is persisted in session metadata.
        Must be derived server-side from the live caller's verified identity (see
        resolve_agent_id_from_email).  When None the session metadata is used with
        a fail-closed default of "callie" (not "artemis").
        - Web-turn path: always set by the route handler from the CF-Access identity.
        - Slack path: None (session metadata is server-authored by route_inbound).
        - Tests: set explicitly to the identity under test.
    """
    # ── 1. Intent shortcut ────────────────────────────────────────────────────
    intent = classify_intent(user_text)
    if intent.kind != IntentKind.NONE:
        shortcut = await handle_observability_intent(intent, owner_user_id=owner_user_id)
        if shortcut is not None:
            await _broadcast(
                session_id,
                {"type": "floating_artemis.turn_started", "session_id": session_id},
            )
            response = shortcut.get("response", "")
            await _broadcast(
                session_id,
                {"type": "floating_artemis.message", "session_id": session_id, "text": response},
            )
            await _broadcast(
                session_id,
                {"type": "floating_artemis.turn_complete", "session_id": session_id},
            )
            # Persist both user message and assistant response
            shortcut_user_msg_id = await _persist_messages(
                session_id=session_id,
                user_text=user_text,
                assistant_text=response,
                user_content=None,
                assistant_content=None,
                usage=Usage(),
                db_session=db_session,
            )
            # M3: write conversation drawer for intent-shortcut turns too (failure-isolated)
            if shortcut_user_msg_id is not None and response:
                try:
                    await write_turn_drawer(
                        user_msg_id=shortcut_user_msg_id,
                        user_text=user_text,
                        assistant_text=response,
                        speaker_name=speaker_name,
                        speaker_id=speaker_id,
                    )
                except Exception:
                    logger.warning(
                        "M3 turn-drawer write failed (shortcut) session_id=%s msg_id=%s",
                        session_id,
                        shortcut_user_msg_id,
                        exc_info=True,
                    )
            return TurnResult(
                session_id=session_id,
                response_text=response,
                stop_reason="end_turn",
                usage=Usage(),
                intent_shortcut=True,
            )

    # ── 2. Get current surfaces ───────────────────────────────────────────────
    try:
        status = await get_status()
        surfaces_list = status.get("available_surfaces", []) if isinstance(status, dict) else []
        all_surfaces: set[str] = set(surfaces_list if isinstance(surfaces_list, list) else [])
    except Exception:
        all_surfaces = set()
    session_ctx = await _load_session_context(
        session_id=session_id,
        db_session=db_session,
        all_surfaces=all_surfaces,
        trusted_agent_id=trusted_agent_id,
    )
    available_surfaces = session_ctx.available_surfaces

    # ── 3. Gather system prompt ingredients (built after history loads in 4a) ──
    agent_profile = load_agent_profile(session_ctx.agent_id)
    # Use the profile-sourced voice corpus (deterministic per session_id).
    voice_samples = select_voice_samples(
        session_id=session_id,
        k=4,
        voice_corpus=agent_profile.voice_corpus,
    )
    page_context_text = await _get_page_context_text(session_id=session_id, db_session=db_session)
    recent_meeting_ctx = await _get_recent_meeting_context(db_session)

    # Part A: OKR reconcile context — only for personal Slack DM turns when a
    # live check-in breadcrumb exists for the speaker.  No-ops for all other turns.
    okr_reconcile_ctx: str | None = None
    if session_ctx.is_personal_slack_dm and speaker_id:
        okr_reconcile_ctx = await _get_okr_reconcile_context(speaker_id, db_session)

    # ── 4. Load history ───────────────────────────────────────────────────────
    history = await _load_message_history(
        session_id=session_id,
        db_session=db_session,
        session_metadata=session_ctx.metadata,
    )

    # ── 4a. Anti-repetition: rebuild system prompt with recent outbound texts ─
    # Extract the last 3-5 assistant text blocks from history so the LLM can
    # actively avoid repeating itself.  Two back-to-back channel-join welcomes
    # will have different recent_outbound_texts even if both start from a cold
    # session, because the first joiner's turn writes to history before the
    # second fires (background tasks run serially per worker).  When history is
    # empty (true cold start) the list is empty and the block is omitted.
    recent_outbound_texts: list[str] = []
    for msg in reversed(history):
        if msg.role == "assistant":
            for block in msg.content:
                if isinstance(block, TextBlock) and block.text.strip():
                    recent_outbound_texts.append(block.text.strip())
                    break  # one text per message is enough
        if len(recent_outbound_texts) >= 4:
            break
    recent_outbound_texts.reverse()  # chronological order for readability

    # Rebuild system prompt with the anti-repetition context now available.
    system_prompt = _build_system_prompt(
        voice_samples=voice_samples,
        page_context=page_context_text,
        available_surfaces=sorted(available_surfaces),
        persona_core=agent_profile.persona_core,
        profile_text=agent_profile.profile_text,
        display_name=agent_profile.display_name,
        agent_id=agent_profile.agent_id,
        recent_meeting_context=recent_meeting_ctx,
        session_id=session_id,
        speaker_name=speaker_name,
        participants=participants,
        is_personal_slack_dm=session_ctx.is_personal_slack_dm,
        okr_reconcile_context=okr_reconcile_ctx,
        recent_outbound_texts=recent_outbound_texts if recent_outbound_texts else None,
    )

    # ── 4b. M4: inject memory context into system prompt ─────────────────────
    # Augment after history load so we can use recent turns as retrieval context.
    system_prompt = await inject_memory_context(
        system_prompt,
        user_text,
        history,
        session_id,
        agent_id=session_ctx.agent_id,
        speaker_name=speaker_name,
        speaker_id=speaker_id,
    )

    if adapter is None:
        resolved = await _resolve_adapter(session_id=session_id, db_session=db_session)
        if isinstance(resolved, str):
            # Provider misconfigured — surface inline, do not crash
            await _broadcast(
                session_id,
                {
                    "type": "floating_artemis.failed",
                    "session_id": session_id,
                    "error": resolved,
                },
            )
            return TurnResult(
                session_id=session_id,
                response_text=None,
                stop_reason="provider_error",
                usage=Usage(),
            )
        adapter = resolved

    # ── 5. Build tool registry ────────────────────────────────────────────────
    # M3: pass agent_id into the registry builder so query_memory is gated to
    # this session's agent allowance.
    # speaker_id is the Slack user id resolved from the inbound event. It
    # authorizes Kai's flag_catalog_gap and is bound into that tool as a closure
    # value, so tool input cannot spoof the requester. None denies (fail-closed).
    auth_registry = _build_tool_registry(
        available_surfaces,
        agent_id=session_ctx.agent_id,
        speaker_id=speaker_id,
    )

    from artemis.providers.claude_code.adapter import ClaudeCodeAdapter

    is_claude_code_with_tools = isinstance(adapter, ClaudeCodeAdapter)

    # Claude Code's MCP path runs tools in a subprocess and cannot surface the
    # in-process layer-3/4 confirmation yield, so we only expose auto-invoke
    # tools there. Other providers keep the full intercepting registry.
    if is_claude_code_with_tools:
        tool_registry = _build_auto_invoke_tool_registry(
            auth_registry, session_id, agent_id=session_ctx.agent_id
        )
    else:
        # Build a plain ToolRegistry that wraps the authorized one for the loop.
        # Layer 3/4 tools get wrapped so we can intercept before execution.
        tool_registry = _build_intercepting_tool_registry(
            auth_registry, session_id, agent_id=session_ctx.agent_id
        )

    # ── 6. Broadcast turn started ─────────────────────────────────────────────
    await _broadcast(
        session_id, {"type": "floating_artemis.turn_started", "session_id": session_id}
    )

    # ── 7. Append user message and run ────────────────────────────────────────
    messages = history + [user_message(user_text)]

    # Set up hooks for broadcasting events
    hooks = HookRegistry()

    async def on_message_hook(msg: Message) -> None:
        if msg.role == "assistant":
            for block in msg.content:
                if isinstance(block, TextBlock):
                    await _broadcast(
                        session_id,
                        {
                            "type": "floating_artemis.message",
                            "session_id": session_id,
                            "text": block.text,
                        },
                    )

    async def before_tool_hook(payload: dict[str, Any]) -> None:
        await _broadcast(
            session_id,
            {
                "type": "floating_artemis.tool_started",
                "session_id": session_id,
                "tool": payload.get("name"),
                "tool_use_id": payload.get("tool_use_id"),
            },
        )

    async def after_tool_hook(payload: dict[str, Any]) -> None:
        await _broadcast(
            session_id,
            {
                "type": "floating_artemis.tool_completed",
                "session_id": session_id,
                "tool": payload.get("name"),
                "tool_use_id": payload.get("tool_use_id"),
                "is_error": payload.get("is_error", False),
            },
        )

    hooks.on("on_message", on_message_hook)
    hooks.on("before_tool", before_tool_hook)
    hooks.on("after_tool", after_tool_hook)

    session_token = floating_session_id_var.set(session_id)
    # SECURITY (M3): bind the subprocess's memory scope to the TRUSTED agent_id
    # (session_ctx.agent_id derives from the live caller's identity), not persisted
    # session metadata — so a non-owner turn on an owner session can't read owner memory.
    trusted_token = floating_trusted_agent_id_var.set(session_ctx.agent_id)
    _turn_start = start_timer()
    try:
        result = await run_turn(
            adapter=adapter,
            messages=messages,
            tools=tool_registry,
            system=system_prompt,
            reasoning_effort=reasoning_effort,
            speed_tier=speed_tier,
            hooks=hooks,
        )
    except _PendingConfirmationError as pending_exc:
        # A layer-3/4 tool was encountered — yield to operator.
        pending = confirmation_store.get(pending_exc.tool_use_id)
        if pending is not None:
            pending.prior_tool_results = [
                block.to_api() for block in getattr(pending_exc, "prior_tool_results", [])
            ]

        await _broadcast(
            session_id,
            {
                "type": "floating_artemis.tool_pending",
                "session_id": session_id,
                "tool_use_id": pending_exc.tool_use_id,
                "tool_name": pending_exc.tool_name,
                "tool_input": pending_exc.tool_input,
                "layer": pending_exc.layer,
            },
        )
        # Persist messages up to this point (user message + assistant tool_use turn)
        await _persist_messages(
            session_id=session_id,
            user_text=user_text,
            assistant_text=None,
            user_content=None,
            assistant_content=_serialize_blocks(pending_exc.assistant_message.content),
            usage=getattr(pending_exc, "usage", Usage()),
            db_session=db_session,
        )
        # Extract text from the assistant's proposal message so Slack/other
        # non-WS surfaces can post it without needing WS broadcast access.
        _proposal_texts = [
            b.text for b in pending_exc.assistant_message.content if isinstance(b, TextBlock)
        ]
        _proposal_text = " ".join(_proposal_texts) if _proposal_texts else None
        return TurnResult(
            session_id=session_id,
            response_text=_proposal_text,
            stop_reason="tool_pending",
            usage=Usage(),
            pending_tool_use_id=pending_exc.tool_use_id,
        )
    except Exception as exc:
        logger.exception("handle_turn failed session_id=%s", session_id)
        await _broadcast(
            session_id,
            {"type": "floating_artemis.failed", "session_id": session_id, "error": str(exc)},
        )
        raise
    finally:
        floating_trusted_agent_id_var.reset(trusted_token)
        floating_session_id_var.reset(session_token)

    # ── 8. Extract final text ─────────────────────────────────────────────────
    response_text: str | None = None
    for msg in reversed(result.messages):
        if msg.role == "assistant":
            texts = [b.text for b in msg.content if isinstance(b, TextBlock)]
            if texts:
                response_text = " ".join(texts)
                break

    # ── 9. Persist messages ────────────────────────────────────────────────────
    user_msg_id = await _persist_messages(
        session_id=session_id,
        user_text=user_text,
        assistant_text=response_text,
        user_content=None,
        assistant_content=None,
        usage=result.usage,
        db_session=db_session,
    )

    # ── 9b. Cost event recording ──────────────────────────────────────────────
    # Derive provider/model from adapter type — never propagate failures.
    try:
        from artemis.providers.claude_code.adapter import ClaudeCodeAdapter

        _fa_provider = "claude-code" if isinstance(adapter, ClaudeCodeAdapter) else "anthropic"
        _fa_model = getattr(adapter, "_default_model", "claude-sonnet-4-6") or "claude-sonnet-4-6"
        _fa_path = "cli" if isinstance(adapter, ClaudeCodeAdapter) else "api"
        import artemis.db as _cost_db

        async with _cost_db.SessionLocal() as _cost_session:
            await record_cost_event(
                _cost_session,
                provider=_fa_provider,
                model=_fa_model,
                provider_path=_fa_path,
                feature_tag="floating_artemis",
                input_tokens=result.usage.input_tokens,
                output_tokens=result.usage.output_tokens,
                cache_creation_input_tokens=result.usage.cache_creation_input_tokens,
                cache_read_input_tokens=result.usage.cache_read_input_tokens,
                source_kind="fa_message",
                session_id=session_id,
            )
            await _cost_session.commit()
    except Exception:
        logger.warning(
            "cost_event recording failed for FA session_id=%s", session_id, exc_info=True
        )

    # ── 9c. M3: auto-write conversation drawer ────────────────────────────────
    # Failure-isolated: drawer write NEVER breaks chat.
    if user_msg_id is not None and response_text is not None:
        try:
            await write_turn_drawer(
                user_msg_id=user_msg_id,
                user_text=user_text,
                assistant_text=response_text,
                agent_id=session_ctx.agent_id,
                speaker_name=speaker_name,
                speaker_id=speaker_id,
            )
        except Exception:
            logger.warning(
                "M3 turn-drawer write failed session_id=%s msg_id=%s",
                session_id,
                user_msg_id,
                exc_info=True,
            )

    # ── 9d. P6: fire-and-forget trace capture ────────────────────────────────
    # Non-blocking; failure is swallowed inside capture_trace. Records a
    # structured per-turn trace row for the self-evolution data foundation.
    try:
        _fa_provider = (
            "claude-code" if "ClaudeCodeAdapter" in type(adapter).__name__ else "anthropic"
        )
        _fa_model = getattr(adapter, "_default_model", None) or "claude-sonnet-4-6"
        # OBS-1: merges the Anthropic ToolUseBlock scan with the claude-code
        # stream-json tool_calls the adapter reports via result.metadata —
        # see _collect_tools_used for why both sources exist.
        _tools_used = _collect_tools_used(result)
        capture_trace(
            agent_id=session_ctx.agent_id,
            # Agent-neutral surface label: handle_turn is the shared conversational
            # turn engine for ALL agents (Artemis/Callie/Kai/…). The specific agent
            # is in agent_id; the surface (slack vs in-app) is derivable from session_id.
            feature_tag="agent_chat",
            session_id=session_id,
            provider=_fa_provider,
            model=_fa_model,
            input_summary=user_text[:500] if user_text else None,
            tools_used=_tools_used,
            output_summary=response_text[:500] if response_text else None,
            outcome="success",
            latency_ms=elapsed_ms(_turn_start),
            input_tokens=result.usage.input_tokens if result.usage else None,
            output_tokens=result.usage.output_tokens if result.usage else None,
            owner_user_id=owner_user_id,
        )
    except Exception:
        logger.debug(
            "P6 trace capture setup failed (non-fatal) session_id=%s", session_id, exc_info=True
        )

    # ── 10. Broadcast completion ──────────────────────────────────────────────
    await _broadcast(
        session_id,
        {
            "type": "floating_artemis.turn_complete",
            "session_id": session_id,
            "stop_reason": result.stop_reason,
        },
    )

    return TurnResult(
        session_id=session_id,
        response_text=response_text,
        stop_reason=result.stop_reason,
        usage=result.usage,
    )


# ── Tool-confirm continuation ─────────────────────────────────────────────────


async def resume_after_confirm(
    *,
    session_id: str,
    tool_use_id: str,
    decision: str,
    adapter: ModelAdapter | None = None,
    db_session: Any | None = None,
    trusted_agent_id: str | None = None,
) -> TurnResult:
    """Resume a suspended turn after operator confirms or cancels a layer-3/4 tool.

    Retrieves pending confirmation, executes (or cancels) the tool, then
    reattaches the conversation and runs to completion.

    Parameters
    ----------
    trusted_agent_id:
        M3 identity binding: when set (web-turn path), this value overrides the
        persisted session metadata for scope gating. Must be derived from the
        live caller's verified identity.  When None (Slack / tests), session
        metadata is used with a fail-closed default of "callie".
    """
    pending = confirmation_store.get(tool_use_id)
    if pending is None:
        raise ValueError(f"No pending confirmation for tool_use_id={tool_use_id!r}")

    # Execute or cancel the tool
    if decision == "run":
        # M3: load session context to get agent_id + surfaces for scope gating.
        # trusted_agent_id (from the live caller's identity) overrides persisted metadata.
        # query_memory is layer-1 and never reaches resume_after_confirm, but we
        # gate consistently in case future layer-2+ tools read memory.
        _resume_agent_id: str | None = None
        _resume_surfaces: set[str] = set()
        try:
            # Mirror the main turn path: load real surfaces first so that
            # surface-gated tools (okr, writing-rules, marketing, jira, granola)
            # are included in the registry — and integration tools (gcal, gmail,
            # slack) are always registered unconditionally via
            # build_authorized_tool_registry.
            try:
                _status = await get_status()
                _surfaces_list = (
                    _status.get("available_surfaces", []) if isinstance(_status, dict) else []
                )
                _resume_surfaces = set(_surfaces_list if isinstance(_surfaces_list, list) else [])
            except Exception:
                _resume_surfaces = set()

            _resume_session_ctx = await _load_session_context(
                session_id=pending.session_id,
                db_session=db_session,
                all_surfaces=_resume_surfaces,
                trusted_agent_id=trusted_agent_id,
            )
            _resume_agent_id = _resume_session_ctx.agent_id
            # Use the surfaces resolved by the session context (may differ from
            # the raw status list after per-session filtering).
            _resume_surfaces = _resume_session_ctx.available_surfaces
        except Exception:
            logger.debug("resume_after_confirm: could not load session context for agent_id")

        # Build the registry from the single canonical source so it is always
        # in sync with the main turn path (includes gcal, gmail, slack, jira,
        # granola — not just the core/okr/writing/marketing subset).
        auth_registry = build_authorized_tool_registry(
            _resume_surfaces,
            agent_id=_resume_agent_id,
        )

        entry = auth_registry.get(pending.tool_name)
        if entry is None:
            tool_result_content = f"Tool '{pending.tool_name}' not found."
            is_error = True
        else:
            try:
                tool_result_content = await entry.impl(pending.tool_input)
                is_error = False
            except Exception as exc:
                tool_result_content = f"{type(exc).__name__}: {exc}"
                is_error = True
    else:
        tool_result_content = "Operator cancelled this action."
        is_error = False

    confirmation_store.resolve(tool_use_id, decision)

    # Build result and resume
    tool_result_block = ToolResultBlock(
        tool_use_id=tool_use_id,
        content=tool_result_content,
        is_error=is_error,
    )
    prior_blocks = [
        ToolResultBlock(
            tool_use_id=str(block.get("tool_use_id", "")),
            content=str(block.get("content", "")),
            is_error=bool(block.get("is_error", False)),
        )
        for block in pending.prior_tool_results
    ]
    tool_result_blocks: list[TextBlock | ToolUseBlock | ToolResultBlock] = [
        *prior_blocks,
        tool_result_block,
    ]

    # Load current history and append the tool_result
    # M3: pass trusted_agent_id so scope gating uses live identity, not stale metadata.
    session_ctx = await _load_session_context(
        session_id=session_id,
        db_session=db_session,
        all_surfaces=set(),
        trusted_agent_id=trusted_agent_id,
    )
    history = await _load_message_history(
        session_id=session_id,
        db_session=db_session,
        session_metadata=session_ctx.metadata,
    )

    # Append a user message containing the tool_result (protocol: tool results are user-role)
    tool_result_msg = Message(role="user", content=tool_result_blocks)
    messages = history + [tool_result_msg]

    if adapter is None:
        resolved = await _resolve_adapter(session_id=session_id, db_session=db_session)
        adapter = resolved if not isinstance(resolved, str) else AnthropicAdapter()

    await _broadcast(
        session_id,
        {
            "type": "floating_artemis.tool_completed",
            "session_id": session_id,
            "tool_use_id": tool_use_id,
            "decision": decision,
            "is_error": is_error,
        },
    )

    session_token = floating_session_id_var.set(session_id)
    # SECURITY (M3): bind the subprocess's memory scope to the TRUSTED agent_id
    # (session_ctx.agent_id derives from the live caller's identity), not persisted
    # session metadata — so a non-owner turn on an owner session can't read owner memory.
    trusted_token = floating_trusted_agent_id_var.set(session_ctx.agent_id)
    try:
        agent_profile = load_agent_profile(session_ctx.agent_id)
        result = await run_turn(
            adapter=adapter,
            messages=messages,
            system=agent_profile.persona_core,
        )
    except Exception as exc:
        await _broadcast(
            session_id,
            {"type": "floating_artemis.failed", "session_id": session_id, "error": str(exc)},
        )
        raise
    finally:
        floating_trusted_agent_id_var.reset(trusted_token)
        floating_session_id_var.reset(session_token)

    response_text: str | None = None
    for msg in reversed(result.messages):
        if msg.role == "assistant":
            texts = [b.text for b in msg.content if isinstance(b, TextBlock)]
            if texts:
                response_text = " ".join(texts)
                break

    if response_text:
        await _broadcast(
            session_id,
            {"type": "floating_artemis.message", "session_id": session_id, "text": response_text},
        )

    await _persist_messages(
        session_id=session_id,
        user_text=None,
        assistant_text=response_text,
        user_content=_serialize_blocks(tool_result_msg.content),
        assistant_content=None,
        usage=result.usage,
        db_session=db_session,
    )

    await _broadcast(
        session_id,
        {"type": "floating_artemis.turn_complete", "session_id": session_id},
    )

    return TurnResult(
        session_id=session_id,
        response_text=response_text,
        stop_reason=result.stop_reason,
        usage=result.usage,
    )


